"""Make logo.h, the coverage table of the OpenWrt logo for ucgfiber-lcd.

usage: mklogo.py LOGO.PNG WIDTH > logo.h

LOGO.PNG is include/logo.png of the OpenWrt tree, WIDTH the width of the
table in pixels. The build does not run this script; logo.h is committed.
Run it by hand when the logo or its size changes. It needs PIL (Pillow).
"""
import sys

from PIL import Image

# Where the tagline under the logo starts, as fractions of the height and
# the width of the picture. These two fit OpenWrt's include/logo.png only.
TAGLINE_TOP = 0.905
TAGLINE_LEFT = 0.425

PER_LINE = 16       # values per line of the table

if len(sys.argv) != 3 or not sys.argv[2].isdigit() or int(sys.argv[2]) < 1:
    sys.exit("usage: mklogo.py LOGO.PNG WIDTH > logo.h")
src, width = sys.argv[1], int(sys.argv[2])

im = Image.open(src).convert('RGBA')
a = im.split()[3]
if a.getextrema()[0] == 255:    # no transparency: take the ink on white
    a = Image.eval(im.convert('L'), lambda v: 255 - v)
w, h = a.size
px = a.load()
# blank the tagline; the descender of the p left of it stays
for y in range(int(h * TAGLINE_TOP), h):
    for x in range(int(w * TAGLINE_LEFT), w):
        px[x, y] = 0
a = a.crop(a.getbbox())
height = round(a.size[1] * width / a.size[0])
a = a.resize((width, height), Image.LANCZOS)

print("""/* SPDX-License-Identifier: GPL-2.0-only */
/*
 * The OpenWrt logo without its tagline: coverage 0..255 of each pixel.
 *
 * Generated by mklogo.py from include/logo.png of the OpenWrt tree.
 * Do not edit.
 */
#ifndef UCGFIBER_LCD_LOGO_H
#define UCGFIBER_LCD_LOGO_H

#include <stdint.h>

#define LOGO_W\t\t%d
#define LOGO_H\t\t%d

static const uint8_t logo_cov[LOGO_H][LOGO_W] = {""" % (width, height))
for y in range(height):
    row = ["%d" % a.getpixel((x, y)) for x in range(width)]
    print("\t{")
    for i in range(0, width, PER_LINE):
        print("\t\t" + ", ".join(row[i:i + PER_LINE]) + ",")
    print("\t},")
print("};\n\n#endif")
